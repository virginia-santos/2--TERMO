-- FASE 1 -DDL
CREATE TABLE CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20) NULL,
    ATIVO BOOLEAN DEFAULT TRUE,

    CONSTRAINT PK_ID_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);
CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL UNIQUE,
   
    CONSTRAINT PK_ID_PLATAFORMA PRIMARY KEY (ID_PLATAFORMA),
    CONSTRAINT UQ_NOME UNIQUE (NOME)
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT,
    DESCRICAO VARCHAR(80) NOT NULL UNIQUE,

    CONSTRAINT PK_ID_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_CATEGORIA_DESCRICAO UNIQUE (DESCRICAO)
);

CREATE TABLE JOGO (
    ID_JOGO INT AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    CODIGO VARCHAR(15) NOT NULL UNIQUE,
    ANO_LANCAMENTO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK (QUANTIDADE_DISPONIVEL >= 0),
    ID_PLATAFORMA INT,
    ID_CATEGORIA INT,

    CONSTRAINT PK_ID_JOGO PRIMARY KEY (ID_JOGO),
    CONSTRAINT FK_PLATAFORMA FOREIGN KEY (ID_PLATAFORMA) REFERENCES PLATAFORMA(ID_PLATAFORMA),
    CONSTRAINT FK_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA(ID_CATEGORIA)
);

CREATE TABLE LOCACAO (
    ID_LOCACAO INT AUTO_INCREMENT,
    DATA_RETIRADA DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NULL,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA' CHECK (STATUS_LOCACAO IN ('ABERTO', 'DEVOLVIDO', 'ATRASADO')),
    ID_CLIENTE INT ,
    ID_JOGO INT,

    CONSTRAINT PK_ID_LOCACAO PRIMARY KEY (ID_LOCACAO),
    CONSTRAINT FK_ID_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_ID_JOGO FOREIGN KEY (ID_JOGO) REFERENCES JOGO (ID_JOGO) ON UPDATE CASCADE ON DELETE RESTRICT
);
