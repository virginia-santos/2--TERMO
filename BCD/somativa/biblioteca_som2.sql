CREATE TABLE USUARIO (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120),
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE
);

-- 3.
CREATE TABLE LIVRO (
    ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0,
    CONSTRAINT CK_QUANTIDADE_DISPONIVEL CHECK (QUANTIDADE_DISPONIVEL >= 0)
);

-- 4.
CREATE TABLE EMPRESTIMO (
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO', CHECK (STATUS_EMPRESTIMO IN ('ABERTO', 'FECHADO')),
    ID_USUARIO INT,
    ID_LIVRO INT,
    CONSTRAINT fk_usuario_cadastrado FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_historico_livro FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO (ID_LIVRO) ON UPDATE CASCADE ON DELETE RESTRICT
   
);

CREATE TABLE GENEROS (
    ID_GENEROS INT PRIMARY KEY AUTO_INCREMENT,
    NOME_GENEROS VARCHAR(100) NOT NULL,
    DESCRICAO TEXT
);

CREATE TABLE FUNCIONARIOS (
    ID_FUNCIONARIOS INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(110) NOT NULL,
    CARGO VARCHAR(100) NOT NULL,
    DATA_NASCIMENTO DATETIME NOT NULL
);

