-- EX 19: PEDIDOS COM O NOME DO CLIENTE
SELECT P.ID_PEDIDO, P.DATA_PEDIDO, C.NOME AS CLIENTE, P.VALOR_TOTAL 
FROM PEDIDO AS P
INNER JOIN cliente AS C 
ON C.ID_CLIENTE = P.ID_CLIENTE

-- OBS: RELACIONE O CLIENTE CUJO ID_CLIENTE É IGUAL ID_CLIENTE GRAVADOS NO PEDIDO
-- ALIASES - SÃO COMO A TRIBUIÇÃO DE PEDIDOS PARA CONSULTAS DE VÁRIAS TABELAS MAIS CURTAS E LEGÍVEIS

-- LEFT JOIN - MANTÉM TODOS OS REGISTROS DA TABELA DA ESQUERDA MESMO QUANDO NÃO POSSUI CORRESPONDÊNCIA

-- EX 20:TODOS OS CLIENTES INCLUSIVE QUE NUNCA COMPROU
SELECT C.NOME, P.ID_PEDIDO, P.DATA_PEDIDO
FROM CLIENTE AS C 
LEFT JOIN pedido AS P
ON P.ID_CLIENTE = C.ID_CLIENTE
ORDER BY C.NOME;

-- EX 21: CLIENTES SEM PEDIDO
SELECT C.ID_CLIENTE, C.NOME 
FROM CLIENTE AS C 
LEFT JOIN pedido AS P 
ON P.ID_CLIENTE = C.ID_CLIENTE
WHERE P.ID_PEDIDO IS NULL;

-- JOIN COM TRÊS TABELAS 
-- EX 22: ITENS DE PEDIDO COM NOME DO PRODUTO
SELECT P.ID_PEDIDO, PR.NOME_PRODUTO AS PRODUTO, IP.QUANTIDADE, IP.PRECO_UNITARIO, IP.QUANTIDADE * IP.PRECO_UNITARIO AS SUBTOTAL
FROM PEDIDO AS P 
INNER JOIN item_pedido AS IP 
ON IP.ID_PEDIDO = P.ID_PEDIDO
INNER JOIN PRODUTO AS PR 
ON PR.ID_PRODUTO = IP.ID_PRODUTO
ORDER BY P.ID_PEDIDO;

-- EX 23: JOIN COM CATEGORIA - PRODUTO E NOME DE SUA CATEGORIA
SELECT PR.`NOME_PRODUTO` AS PRODUTO, CA.`NOME_CATEGORIA` AS CATEGORIA, PR.PRECO 
FROM PRODUTO AS PR
INNER JOIN CATEGORIA AS CA 
ON CA.ID_CATEGORIA = PR.ID_CATEGORIA
ORDER BY CA.`NOME_CATEGORIA`, PR.`NOME_PRODUTO`;

-- AGREGANDO JOINS
-- 24 - QUANTIDADE DE PRODUOS POR CATEGORIA
SELECT CA.NOME_CATEGORIA AS CATEGORIA, COUNT (PR.ID_PRODUTO) AS QTDE_PRODUTOS
FROM CATEGORIA AS CA 
LEFT JOIN PRODUTO AS PR 
ON PR.`ID_CATEGORIA` = CA.`ID_CATEGORIA`
GROUP BY CA.`ID_CATEGORIA`, CA.`NOME_CATEGORIA`
ORDER BY QTDE_PRODUTOS DESC

-- EX 25: TOTAL COMPRADO POR CLIENTE
SELECT C.NOME AS CLIENTE, COUNT(P.ID_PEDIDO) AS QTDE_PEDIDOS,
SUM(P.VALOR_TOTAL) AS TOTAL_COMPRADO
FROM CLIENTE AS C 
INNER JOIN PEDIDO AS P
ON P.`ID_CLIENTE` = C.`ID_CLIENTE`
GROUP BY C.`ID_CLIENTE`, C.NOME

-- EX 26: COMBINAÇÃO DE VÁRIAS TABELAS PARA UMA CONSULTA COMPLETA 
SELECT P.ID_PEDIDO, DATE_FORMAT(P.DATA_PEDIDO, '%d %m %Y %H %i') AS DATA, C.`NOME` AS CLIENTE, PR.`NOME_PRODUTO` AS PRODUTO, IP.QUANTIDADE, IP.PRECO_UNITARIO, IP.QUANTIDADE * IP.PRECO_UNITARIO AS SUBTOTAL
FROM PEDIDO AS P 
INNER JOIN CLIENTE AS C
ON C.`ID_CLIENTE` = P.`ID_CLIENTE`
INNER JOIN item_pedido AS IP 
ON IP.`ID_PEDIDO` = P.`ID_PEDIDO`
INNER JOIN PRODUTO AS PR 
ON PR.`ID_PRODUTO` = IP.`ID_PRODUTO`
ORDER BY P.`ID_PEDIDO`, PR.`NOME_PRODUTO`;

-- OBS: DATE_FORMAT(P.DATA_PEDIDO, '%d %m %Y %H %i') - FORMATAÇAÕ PADRÃO BRASIL
